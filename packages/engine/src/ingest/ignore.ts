/**
 * Which files take part in analysis.
 *
 * Exclusions are reported in scan coverage, never silent. Dependency
 * directories and build output are excluded from analysis but their manifests
 * and lockfiles are kept, because that is where dependency findings come from.
 */

const EXCLUDED_DIRS = new Set([
  'node_modules', '.git', '.hg', '.svn', 'dist', 'build', 'out', '.next', '.nuxt',
  '.svelte-kit', '.turbo', '.cache', '.parcel-cache', 'coverage', '.nyc_output',
  '__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache', '.tox',
  'venv', '.venv', 'env', 'vendor', 'target', 'bin', 'obj', '.gradle',
  '.idea', '.vscode', '.terraform', '.serverless', 'Pods', '.dart_tool',
  'bower_components', 'jspm_packages', '.yarn', '.pnpm-store', '.output',
]);

/** Binary and asset extensions: indexed as assets, never parsed. */
const BINARY_EXT = new Set([
  'png','jpg','jpeg','gif','webp','avif','ico','bmp','tiff','svgz',
  'mp4','mov','avi','webm','mkv','mp3','wav','flac','ogg','m4a',
  'zip','gz','tgz','bz2','xz','7z','rar','tar','jar','war','whl',
  'pdf','doc','docx','xls','xlsx','ppt','pptx',
  'woff','woff2','ttf','otf','eot',
  'so','dylib','dll','exe','bin','o','a','class','pyc','pyo','wasm',
  'db','sqlite','sqlite3','mmdb','pack','idx','node',
]);

const LOCKFILES = new Set([
  'package-lock.json','pnpm-lock.yaml','yarn.lock','bun.lockb','npm-shrinkwrap.json',
  'poetry.lock','Pipfile.lock','uv.lock','requirements.txt','Gemfile.lock',
  'composer.lock','go.sum','Cargo.lock','packages.lock.json','gradle.lockfile',
]);

/** Generated-code markers found in the first few lines of a file. */
const GENERATED_MARKERS = [
  '@generated', 'do not edit', 'do not modify', 'auto-generated', 'autogenerated',
  'code generated by', 'this file was automatically generated', 'generated by protoc',
];

export function isExcludedDir(segment: string): boolean {
  return EXCLUDED_DIRS.has(segment);
}

export function extensionOf(path: string): string {
  const base = path.slice(path.lastIndexOf('/') + 1);
  const i = base.lastIndexOf('.');
  return i <= 0 ? '' : base.slice(i + 1).toLowerCase();
}

export function basenameOf(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

export function isBinaryPath(path: string): boolean {
  return BINARY_EXT.has(extensionOf(path));
}

export function isLockfile(path: string): boolean {
  return LOCKFILES.has(basenameOf(path));
}

/**
 * True when the path sits inside an excluded directory. Manifests and lockfiles
 * are kept even inside dependency directories so dependency analysis still has
 * its inputs.
 */
export function isExcludedPath(path: string): { excluded: boolean; reason?: string } {
  const segments = path.split('/');
  for (const s of segments.slice(0, -1)) {
    if (isExcludedDir(s)) {
      if (isLockfile(path) || basenameOf(path) === 'package.json') {
        return { excluded: false };
      }
      return { excluded: true, reason: `inside excluded directory '${s}'` };
    }
  }
  if (segments.some((s) => s.startsWith('.') && s.length > 1 && isExcludedDir(s))) {
    return { excluded: true, reason: 'hidden tooling directory' };
  }
  return { excluded: false };
}

/** Heuristic: is this file machine-generated? Checked against content, not just name. */
export function looksGenerated(path: string, head: string): boolean {
  const base = basenameOf(path).toLowerCase();
  if (base.endsWith('.min.js') || base.endsWith('.min.css')) return true;
  if (base.endsWith('.d.ts') && head.includes('@generated')) return true;
  if (/\.(pb|generated|gen)\.(ts|js|go|py|java|cs)$/.test(base)) return true;
  if (isLockfile(path)) return true;
  const lower = head.slice(0, 1500).toLowerCase();
  return GENERATED_MARKERS.some((m) => lower.includes(m));
}

export function looksVendored(path: string): boolean {
  return /(^|\/)(vendor|third_party|thirdparty|external|deps)\//.test(path);
}
